CREATE TABLE tickets (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id INTEGER REFERENCES departments (id) ON DELETE SET NULL,
    name TEXT NOT NULL DEFAULT '',
    manager_user_uuid UUID REFERENCES managers (user_uuid) ON DELETE SET NULL,
    client_user_uuid UUID NOT NULL REFERENCES clients (user_uuid) ON DELETE RESTRICT,
    status ticket_status NOT NULL DEFAULT 'new',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT tickets_distinct_participants_chk CHECK (
        manager_user_uuid IS NULL OR manager_user_uuid <> client_user_uuid
    )
);

CREATE TABLE messages (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id INTEGER NOT NULL REFERENCES tickets (id) ON DELETE CASCADE,
    recipient_user_uuid UUID NOT NULL REFERENCES users (uuid) ON DELETE RESTRICT,
    from_type msg_from_type NOT NULL,
    text BYTEA NOT NULL,
    status msg_status NOT NULL DEFAULT 'sent',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT messages_text_not_empty_chk CHECK (octet_length(text) > 0)
);

CREATE TABLE message_files (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    msg_id INTEGER NOT NULL REFERENCES messages (id) ON DELETE CASCADE,
    file_name TEXT NOT NULL,
    path TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT message_files_name_not_blank_chk CHECK (btrim(file_name) <> ''),
    CONSTRAINT message_files_path_not_blank_chk CHECK (btrim(path) <> '')
);

CREATE TABLE refresh_tokens (
    jti UUID PRIMARY KEY,
    user_uuid UUID NOT NULL UNIQUE REFERENCES users (uuid) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL DEFAULT (CURRENT_TIMESTAMP + INTERVAL '30 days'),
    CONSTRAINT refresh_tokens_expires_after_created_chk CHECK (expires_at > created_at)
);

