CREATE OR REPLACE FUNCTION assert_user_role()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    actual_role user_role;
BEGIN
    SELECT u.role
    INTO actual_role
    FROM users AS u
    WHERE u.uuid = NEW.user_uuid;

    IF actual_role IS NULL THEN
        RAISE EXCEPTION 'user % does not exist', NEW.user_uuid
            USING ERRCODE = '23503';
    END IF;

    IF actual_role::TEXT <> TG_ARGV[0] THEN
        RAISE EXCEPTION 'user % must have role %, got %', NEW.user_uuid, TG_ARGV[0], actual_role
            USING ERRCODE = '23514';
    END IF;

    RETURN NEW;
END;
$$;
-- +goose StatementEnd

