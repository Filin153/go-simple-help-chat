CREATE OR REPLACE FUNCTION validate_message_recipient()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    ticket_client_uuid UUID;
    ticket_manager_uuid UUID;
BEGIN
    SELECT t.client_user_uuid, t.manager_user_uuid
    INTO ticket_client_uuid, ticket_manager_uuid
    FROM tickets AS t
    WHERE t.id = NEW.ticket_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'ticket % does not exist', NEW.ticket_id
            USING ERRCODE = '23503';
    END IF;

    CASE NEW.from_type
        WHEN 'manager' THEN
            IF NEW.recipient_user_uuid IS DISTINCT FROM ticket_client_uuid THEN
                RAISE EXCEPTION 'manager message recipient must be ticket client %', ticket_client_uuid
                    USING ERRCODE = '23514';
            END IF;
        WHEN 'client' THEN
            IF ticket_manager_uuid IS NULL THEN
                RAISE EXCEPTION 'ticket % does not have an assigned manager', NEW.ticket_id
                    USING ERRCODE = '23514';
            END IF;

            IF NEW.recipient_user_uuid IS DISTINCT FROM ticket_manager_uuid THEN
                RAISE EXCEPTION 'client message recipient must be ticket manager %', ticket_manager_uuid
                    USING ERRCODE = '23514';
            END IF;
        WHEN 'system' THEN
            IF NEW.recipient_user_uuid IS DISTINCT FROM ticket_client_uuid
               AND (ticket_manager_uuid IS NULL OR NEW.recipient_user_uuid IS DISTINCT FROM ticket_manager_uuid) THEN
                RAISE EXCEPTION 'system message recipient must be one of the ticket participants'
                    USING ERRCODE = '23514';
            END IF;
    END CASE;

    RETURN NEW;
END;
$$;
