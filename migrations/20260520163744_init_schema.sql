CREATE TYPE user_role AS ENUM ('admin', 'manager', 'client');
CREATE TYPE ticket_status AS ENUM ('new', 'in_work', 'have_unread', 'ready', 'next_department');
CREATE TYPE msg_from_type AS ENUM ('manager', 'client', 'system');
CREATE TYPE msg_status AS ENUM ('draft', 'sent', 'read');

CREATE TABLE users (
    uuid UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    login CITEXT NOT NULL UNIQUE,
    password TEXT NOT NULL,
    role user_role NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT users_login_not_blank_chk CHECK (btrim(login::TEXT) <> ''),
    CONSTRAINT users_password_not_blank_chk CHECK (btrim(password) <> '')
);

CREATE TABLE departments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name CITEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT departments_name_not_blank_chk CHECK (btrim(name::TEXT) <> '')
);

CREATE TABLE clients (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_uuid UUID NOT NULL UNIQUE REFERENCES users (uuid) ON DELETE CASCADE,
    info JSONB NOT NULL DEFAULT '{}'::JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT clients_info_object_chk CHECK (jsonb_typeof(info) = 'object')
);

CREATE TABLE managers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id INTEGER NOT NULL REFERENCES departments (id) ON DELETE RESTRICT,
    user_uuid UUID NOT NULL UNIQUE REFERENCES users (uuid) ON DELETE CASCADE,
    name TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT managers_name_not_blank_chk CHECK (btrim(name) <> '')
);

CREATE TABLE schedules (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id INTEGER NOT NULL REFERENCES departments (id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    work_from TIMESTAMPTZ NOT NULL,
    work_to TIMESTAMPTZ NOT NULL,
    break_from TIMESTAMPTZ NOT NULL,
    break_to TIMESTAMPTZ NOT NULL,
    is_week_end BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT schedules_name_not_blank_chk CHECK (btrim(name) <> ''),
    CONSTRAINT schedules_work_window_chk CHECK (work_from < work_to),
    CONSTRAINT schedules_break_window_chk CHECK (break_from < break_to),
    CONSTRAINT schedules_break_inside_work_chk CHECK (break_from >= work_from AND break_to <= work_to),
    CONSTRAINT schedules_single_day_chk CHECK (
        date_trunc('day', work_from) = date_trunc('day', work_to)
        AND date_trunc('day', work_from) = date_trunc('day', break_from)
        AND date_trunc('day', work_from) = date_trunc('day', break_to)
    )
);

