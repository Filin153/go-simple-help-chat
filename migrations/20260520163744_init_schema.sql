CREATE OR REPLACE FUNCTION protect_user_role_change()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.role = OLD.role THEN
        RETURN NEW;
    END IF;

    IF EXISTS (SELECT 1 FROM managers WHERE user_uuid = NEW.uuid)
       AND NEW.role <> 'manager' THEN
        RAISE EXCEPTION 'user % has manager profile and cannot switch to role %', NEW.uuid, NEW.role
            USING ERRCODE = '23514';
    END IF;

    IF EXISTS (SELECT 1 FROM clients WHERE user_uuid = NEW.uuid)
       AND NEW.role <> 'client' THEN
        RAISE EXCEPTION 'user % has client profile and cannot switch to role %', NEW.uuid, NEW.role
            USING ERRCODE = '23514';
    END IF;

    RETURN NEW;
END;
$$;
