CREATE OR REPLACE FUNCTION purge_expired_refresh_tokens()
RETURNS INTEGER
LANGUAGE plpgsql
AS $$
DECLARE
    deleted_count INTEGER;
BEGIN
    WITH deleted AS (
        DELETE FROM refresh_tokens
        WHERE expires_at <= CURRENT_TIMESTAMP
        RETURNING 1
    )
    SELECT COUNT(*)
    INTO deleted_count
    FROM deleted;

    RETURN deleted_count;
END;
$$;
-- +goose StatementEnd

-- +goose StatementBegin
CREATE OR REPLACE FUNCTION cleanup_expired_refresh_tokens_trigger()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    PERFORM purge_expired_refresh_tokens();

    IF NEW.expires_at <= CURRENT_TIMESTAMP THEN
        RAISE EXCEPTION 'refresh token expires_at must be in the future'
            USING ERRCODE = '23514';
    END IF;

    RETURN NEW;
END;
$$;
