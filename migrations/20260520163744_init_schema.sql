CREATE OR REPLACE FUNCTION validate_ticket_manager_department()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    manager_department_id INTEGER;
BEGIN
    IF NEW.manager_user_uuid IS NULL THEN
        RETURN NEW;
    END IF;

    IF NEW.department_id IS NULL THEN
        RAISE EXCEPTION 'department_id is required when manager_user_uuid is set'
            USING ERRCODE = '23514';
    END IF;

    SELECT m.department_id
    INTO manager_department_id
    FROM managers AS m
    WHERE m.user_uuid = NEW.manager_user_uuid;

    IF manager_department_id IS NULL THEN
        RAISE EXCEPTION 'manager % does not exist', NEW.manager_user_uuid
            USING ERRCODE = '23503';
    END IF;

    IF manager_department_id <> NEW.department_id THEN
        RAISE EXCEPTION 'manager % belongs to department %, ticket department is %',
            NEW.manager_user_uuid, manager_department_id, NEW.department_id
            USING ERRCODE = '23514';
    END IF;

    RETURN NEW;
END;
$$;
